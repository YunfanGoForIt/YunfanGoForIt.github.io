const root = document.documentElement;
const menuBtn = document.querySelector(".menu-btn");
const langButtons = document.querySelectorAll("[data-lang-set]");

function applyLang(lang) {
  const dict = copy[lang] || copy.zh;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (dict[key]) el.setAttribute("aria-label", dict[key]);
  });
  root.lang = lang === "en" ? "en" : "zh-CN";
  document.title = dict.pageTitle;
  langButtons.forEach((btn) => {
    btn.setAttribute("aria-pressed", String(btn.dataset.langSet === lang));
  });
  localStorage.setItem("site-lang", lang);
}

function closeNav() {
  document.body.classList.remove("nav-open");
  if (menuBtn) menuBtn.setAttribute("aria-expanded", "false");
}

const saved = localStorage.getItem("site-lang");
const startLang = saved || (navigator.language && navigator.language.toLowerCase().startsWith("zh") ? "zh" : "zh");
applyLang(startLang);

langButtons.forEach((btn) => {
  btn.addEventListener("click", () => {
    applyLang(btn.dataset.langSet);
    closeNav();
  });
});

if (menuBtn) {
  menuBtn.addEventListener("click", () => {
    const open = document.body.classList.toggle("nav-open");
    menuBtn.setAttribute("aria-expanded", String(open));
  });
}

document.querySelectorAll('.nav-links a[href^="#"]').forEach((link) => {
  link.addEventListener("click", closeNav);
});

document.getElementById("year").textContent = String(new Date().getFullYear());
